export const getPracticeContentType = (
  exampleId: PracticeTabExampleId,
): PracticeContentType =>
  practiceDrillExampleIds.has(exampleId) ? "drill" : "musical-exercise";

export type PracticeExerciseMetadata = {
  difficulty: PracticeDifficulty;
  familyId: string;
  familyLevel: number;
  focus: string;
  genres: readonly PracticeGenre[];
  musicalContext?: { root: TonicName; scale: ScaleName };
  techniques: readonly [PracticeTechnique, ...PracticeTechnique[]];
  tempo: { min: number; recommended: number; target: number };
};

const meta = (
  genres: readonly PracticeGenre[],
  techniques: PracticeExerciseMetadata["techniques"],
  difficulty: PracticeDifficulty,
  familyId: string,
  familyLevel: number,
  focus: string,
  recommended: number,
  target: number,
  musicalContext?: PracticeExerciseMetadata["musicalContext"],
  minimum = Math.max(30, recommended - 20),
): PracticeExerciseMetadata => ({
  difficulty,
  familyId,
  familyLevel,
  focus,
  genres,
  musicalContext,
  techniques,
  tempo: { min: minimum, recommended, target },
});

